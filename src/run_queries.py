"""Run the example queries of eval/queries.yaml.

Usage
  python3 src/run_queries.py                       # retrieval check -> results/queries/RETRIEVAL.md
  python3 src/run_queries.py --agent local         # Goose + local Ollama model   -> results/agent_runs/local/
  python3 src/run_queries.py --agent deepseek      # Goose + DeepSeek API         -> results/agent_runs/deepseek/
  python3 src/run_queries.py --agent course:qwen   # course wrapper (Yandex, 3M tokens/day)
  python3 src/run_queries.py --agent local --model qwen3:8b --ids q1,q3
  python3 src/run_queries.py --rescore local       # re-check saved transcripts, no agent calls
  python3 src/run_queries.py --table               # comparison table (+ your grades) -> REPORT.md

Retrieval check: runs src/search.py for each query and records whether an expected
paper is among the top 5 hits (for the negative test: whether the search is empty).

Agent runs: for local/deepseek calls `python3 src/agent.py --backend <b> run "<question>"`,
for course:<alias> calls `ai4science -m <alias> run "<question>"`, in the repository root.
It saves each transcript, and checks every citation
it printed: the file must exist, its key must be in the catalog, and the line range
must lie inside the file. Correctness of the content is graded by hand in REPORT.md.
"""
import argparse
import datetime as dt
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
QUERIES = ROOT / "eval" / "queries.yaml"
CITE = re.compile(r"(literature/md/([\w.-]+)\.md):L(\d+)-L(\d+)")
PROMPT_SUFFIX = (" Answer from the local library, following AGENT.md: search first, read the passages, "
                 "cite every claim with file and line range, end with a Verification line, "
                 "and append an entry to diary.md.")


def load_queries(ids=None):
    qs = yaml.safe_load(QUERIES.read_text(encoding="utf-8"))["queries"]
    return [q for q in qs if not ids or q["id"] in ids]


def retrieval(queries):
    rows, body = [], []
    for q in queries:
        cmd = [sys.executable, "src/search.py", *q["search"], "-k", "5", "--json"]
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        error = (r.stderr or r.stdout).strip() if r.returncode != 0 else ""
        hits = json.loads(r.stdout or "[]") if not error else []
        keys = [h["key"] for h in hits]
        ok = not error and ((not hits) if q["expect"] == "none" else any(k in keys for k in q["expect"]))
        rows.append((q["id"], ok))
        shown = " ".join(f'"{a}"' if " " in a or "|" in a else a for a in q["search"])
        body.append(f"## {q['id']}. {q['question']}\n")
        body.append(f"`python3 src/search.py {shown} -k 5`\n")
        body.append(f"Expected: {'no hits (negative test)' if q['expect'] == 'none' else ', '.join(q['expect'])}"
                    f" — **{'PASS' if ok else 'FAIL'}**\n")
        body.extend(f"{h['rank']}. `{h['citation']}` (score {h['score']})" for h in hits)
        if error:
            body.append(f"_Search error: {error}_")
        elif not hits:
            body.append("_No results._")
        body.append("")
    n_ok = sum(ok for _, ok in rows)
    head = [
        "# Retrieval check of the example queries",
        "",
        f"Generated by `python3 src/run_queries.py` on {dt.datetime.now():%Y-%m-%d %H:%M}. "
        f"Passed: **{n_ok}/{len(rows)}** (an expected paper in the top 5, or an empty result for the negative test).",
        "",
        "| Query | Result |", "|---|---|",
        *[f"| {i} | {'PASS' if ok else 'FAIL'} |" for i, ok in rows], "",
    ]
    out = ROOT / "results" / "queries" / "RETRIEVAL.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(head + body) + "\n", encoding="utf-8")
    print(f"Retrieval: {n_ok}/{len(rows)} passed -> {out.relative_to(ROOT)}")


def check_citations(text, catalog_keys):
    found, bad = [], []
    for path, key, a, b in CITE.findall(text):
        a, b = int(a), int(b)
        f = ROOT / path
        n = len(f.read_text(encoding="utf-8").splitlines()) if f.exists() else 0
        ok = key in catalog_keys and f.exists() and 1 <= a <= b <= n
        (found if ok else bad).append(f"{path}:L{a}-L{b}")
    return found, bad


def agent_command(spec, model):
    """Return (command prefix, label) for an agent spec: local | deepseek | course:<alias>."""
    if spec.startswith("course:"):
        exe = shutil.which("ai4science")
        if not exe:
            sys.exit("`ai4science` not found on PATH. Install the course agent: https://github.com/andkhalov/AI4Science")
        alias = spec.split(":", 1)[1]
        return [exe, "-m", alias, "run"], f"course-{alias}"
    if spec not in ("local", "deepseek"):
        sys.exit(f"unknown agent '{spec}': use local, deepseek or course:<alias>")
    cmd = [sys.executable, "src/agent.py", "--backend", spec] + (["--model", model] if model else []) + ["run"]
    label = spec + (f"-{re.sub(r'[^A-Za-z0-9.]+', '-', model)}" if model else "")
    return cmd, label


NOT_FOUND = re.compile(r"not\s+found|no\s+(?:results|matches|hits)|none\s+of\s+(?:my|your|the)|"
                       r"(?:do|does)\s+not\s+(?:use|mention|appear)|no\s+(?:paper|evidence)", re.I)
LOOSE_REF = re.compile(r"literature/md/([\w.-]+)\.md(?!:L\d)")
USAGE = ROOT / "results" / "agent_runs" / "usage.jsonl"
DIARY = ROOT / "diary.md"
GRADE_HELP = ("# Replace each 'todo' with yes | partial | no, grading the answer against `expected` in eval/queries.yaml\n"
              "# Then run: python3 src/run_queries.py --table   (fills the table in REPORT.md)\n")


def _lines(path):
    return path.read_text(encoding="utf-8").splitlines() if path.exists() else []


def _diary_entries():
    return sum(1 for l in _lines(DIARY) if l.startswith("## "))


def score(q, text, keys):
    """Automatic checks on one transcript."""
    good, bad = check_citations(text, keys)
    loose = sorted({m for m in LOOSE_REF.findall(text)})
    return {
        "id": q["id"],
        "citations": len(set(good)), "invalid": len(set(bad)), "invalid_list": sorted(set(bad)),
        "refs_without_lines": loose,
        "searches": len(re.findall(r"src/search\.py", text)),
        "verification": bool(re.search(r"verification", text, re.I)),
        "not_found": bool(NOT_FOUND.search(text)) if q["expect"] == "none" else None,
    }


def write_summary(out_dir, label, spec, model, rows):
    head = ["| Query | Searches | Citations | Invalid | File refs without lines | Verification | Diary entry | Tokens | Not-found (q3) |",
            "|---|---|---|---|---|---|---|---|---|"]
    fmt = lambda v: "-" if v is None else ("yes" if v is True else "no" if v is False else str(v))
    body = [f"| {r['id']} | {r['searches']} | {r['citations']} | {r['invalid']} | {', '.join(r['refs_without_lines']) or '-'} "
            f"| {fmt(r['verification'])} | {fmt(r.get('diary'))} | {fmt(r.get('tokens'))} | {fmt(r['not_found'])} |" for r in rows]
    (out_dir / "summary.json").write_text(json.dumps({"label": label, "spec": spec, "model": model, "rows": rows},
                                                     indent=1), encoding="utf-8")
    (out_dir / "SUMMARY.md").write_text(
        f"# Agent runs: `{label}`\n\nGenerated by `python3 src/run_queries.py --agent {spec}"
        + (f" --model {model}" if model else "") + "`. Automatic checks only; grade correctness in "
        f"`{out_dir.relative_to(ROOT)}/grades.yaml`, then run `python3 src/run_queries.py --table`.\n\n"
        "- *Searches*: calls of src/search.py visible in the transcript.\n"
        "- *File refs without lines*: papers named without an `:Lstart-Lend` range (not checkable).\n"
        "- *Diary entry*: diary.md gained an entry during this query.\n\n"
        + "\n".join(head + body) + "\n", encoding="utf-8")
    grades = out_dir / "grades.yaml"                       # keep existing grades, add missing queries
    text = grades.read_text(encoding="utf-8") if grades.exists() else GRADE_HELP
    have = set(re.findall(r"^(\w+):", text, re.M))
    missing = "".join(f"{r['id']}: todo\n" for r in rows if r["id"] not in have)
    if missing or not grades.exists():
        grades.write_text(text.rstrip("\n") + "\n" + missing, encoding="utf-8")


def agent(queries, spec, model=None):
    prefix, label = agent_command(spec, model)
    keys = {p["key"] for p in yaml.safe_load((ROOT / "literature" / "catalog.yaml").read_text(encoding="utf-8"))["papers"]}
    out_dir = ROOT / "results" / "agent_runs" / label
    out_dir.mkdir(parents=True, exist_ok=True)
    rows = []
    for q in queries:
        print(f"{q['id']}: asking {label} ...", flush=True)
        n_usage, n_diary = len(_lines(USAGE)), _diary_entries()
        r = subprocess.run(prefix + [q["question"] + PROMPT_SUFFIX],
                           cwd=ROOT, capture_output=True, text=True, timeout=1800)
        err = r.stderr if r.returncode else "\n".join(l for l in r.stderr.splitlines() if l.startswith("[agent]"))
        text = re.sub(r"\x1b\[[0-9;]*[A-Za-z]", "", r.stdout + ("\n" + err if err else ""))
        row = score(q, text, keys)
        usage = [json.loads(l) for l in _lines(USAGE)[n_usage:] if l.strip()]
        row["tokens"] = sum((u.get("prompt_tokens") or 0) + (u.get("completion_tokens") or 0) for u in usage) if usage else None
        row["diary"] = _diary_entries() > n_diary
        rows.append(row)
        (out_dir / f"{q['id']}.md").write_text(
            f"# {q['id']}. {q['question']}\n\n- Agent: `{label}`\n- Date: {dt.datetime.now():%Y-%m-%d %H:%M}\n"
            f"- Valid citations: {row['citations']}; invalid: {row['invalid']} {row['invalid_list'] or ''}\n"
            f"- Tokens: {row['tokens']}; diary entry: {row['diary']}\n"
            f"- Expected (gist): {q['expected']}\n\n## Transcript\n\n```text\n{text.strip()}\n```\n", encoding="utf-8")
        write_summary(out_dir, label, spec, model, rows)      # after every query, so a crash keeps results
    print(f"Transcripts -> {out_dir.relative_to(ROOT)}/  (grade answers in grades.yaml)")


def rescore(label):
    """Recompute automatic checks from saved transcripts (no agent calls)."""
    out_dir = ROOT / "results" / "agent_runs" / label
    keys = {p["key"] for p in yaml.safe_load((ROOT / "literature" / "catalog.yaml").read_text(encoding="utf-8"))["papers"]}
    old = json.loads((out_dir / "summary.json").read_text()) if (out_dir / "summary.json").exists() else {}
    prev = {r["id"]: r for r in old.get("rows", [])}
    rows = []
    for q in load_queries():
        f = out_dir / f"{q['id']}.md"
        if not f.exists():
            continue
        md = f.read_text(encoding="utf-8")
        text = md.split("## Transcript", 1)[-1]
        row = score(q, text, keys)
        row["tokens"] = prev.get(q["id"], {}).get("tokens")
        row["diary"] = prev.get(q["id"], {}).get("diary")
        rows.append(row)
    if not rows:
        sys.exit(f"No transcripts in {out_dir.relative_to(ROOT)}/")
    write_summary(out_dir, label, old.get("spec", label.split("-")[0]), old.get("model"), rows)
    print(f"Rescored {len(rows)} transcripts -> {out_dir.relative_to(ROOT)}/SUMMARY.md")


AGENT_NAMES = {"local": "Goose + Qwen3-Coder-30B-A3B FP8 (local, vLLM)", "deepseek": "Goose + DeepSeek API"}


def table():
    """Build the comparison table from summary.json + grades.yaml of every run; update REPORT.md."""
    runs = sorted((ROOT / "results" / "agent_runs").glob("*/summary.json"))
    if not runs:
        sys.exit("No agent runs yet. Run: python3 src/run_queries.py --agent local")
    out = ["| Agent | Correct (yes / partial / no) | Valid / invalid citations | Searched before answering | "
           "Verification line | Diary entry | q3 answered \"not found\" | Tokens |",
           "|---|---|---|---|---|---|---|---|"]
    for f in runs:
        d = json.loads(f.read_text(encoding="utf-8"))
        rows, n = d["rows"], len(d["rows"])
        gfile = f.parent / "grades.yaml"
        g = {k: v.lower() for k, v in re.findall(r"^(\w+):\s*(\w+)", gfile.read_text(encoding="utf-8"), re.M)} \
            if gfile.exists() else {}
        graded = [g.get(r["id"]) for r in rows if g.get(r["id"]) in ("yes", "partial", "no")]
        correct = (f"{graded.count('yes')} / {graded.count('partial')} / {graded.count('no')}"
                   + (f" ({n - len(graded)} ungraded)" if len(graded) < n else ""))
        diary = [r.get("diary") for r in rows]
        tokens = [r.get("tokens") for r in rows]
        q3 = next((r["not_found"] for r in rows if r["not_found"] is not None), None)
        name = AGENT_NAMES.get(d.get("spec"), d["label"]) + (f" `{d['model']}`" if d.get("model") else "")
        out.append(
            f"| {name} | {correct} | {sum(r['citations'] for r in rows)} / {sum(r['invalid'] for r in rows)} "
            f"| {sum(r['searches'] > 0 for r in rows)}/{n} | {sum(r['verification'] for r in rows)}/{n} "
            f"| {'n/a' if all(x is None for x in diary) else f'{sum(bool(x) for x in diary)}/{n}'} "
            f"| {'-' if q3 is None else 'yes' if q3 else 'no (check transcript)'} "
            f"| {'n/a' if all(t is None for t in tokens) else f'{sum(t or 0 for t in tokens):,}'} |")
    md = "\n".join(out)
    print(md)
    rep = ROOT / "REPORT.md"
    s = rep.read_text(encoding="utf-8")
    a, b = "<!-- RESULTS:BEGIN -->", "<!-- RESULTS:END -->"
    if a in s and b in s:
        head, rest = s.split(a, 1)
        rep.write_text(f"{head}{a}\n{md}\n{b}{rest.split(b, 1)[1]}", encoding="utf-8")
        print("\nREPORT.md table updated.")


def main():
    ap = argparse.ArgumentParser(description="Run eval/queries.yaml.")
    ap.add_argument("--agent", metavar="SPEC", help="local | deepseek | course:<alias> (e.g. course:qwen)")
    ap.add_argument("--model", help="model name for local/deepseek (default from .env / src/agent.py)")
    ap.add_argument("--ids", help="comma-separated query ids, e.g. q1,q3")
    ap.add_argument("--rescore", metavar="LABEL", help="recompute checks from saved transcripts, e.g. local")
    ap.add_argument("--table", action="store_true", help="comparison table from all runs (+ grades) -> REPORT.md")
    a = ap.parse_args()
    if a.rescore:
        return rescore(a.rescore)
    if a.table:
        return table()
    qs = load_queries(set(a.ids.split(",")) if a.ids else None)
    agent(qs, a.agent, a.model) if a.agent else retrieval(qs)


if __name__ == "__main__":
    main()
